# ---------- T029: optional Unicode shaping and bidi (D033, docs/TEXT_LAYOUT.md §5) ----------
#
# Provider: HarfBuzz_jll — a thin ccall surface over the harfbuzz C API
# (blob → face → font → buffer → hb_shape). Loaded lazily on first use
# (D028 pattern); core-only environments and the legacy LTR `typeset`
# path never load it.
#
# Verified ABI (T029 probe; C offsetof/sizeof against both the system
# libharfbuzz 12.3.2 and the JLL 15.1.0 artifact — identical for all of
# the following):
#   hb_glyph_info_t     = 5 x uint32: gid@0, mask@4, cluster@8
#   hb_glyph_position_t = 5 x int32:  x_advance@0, y_advance@4,
#                                    x_offset@8, y_offset@12
#   hb_direction_t LTR=4, RTL=5; hb_script_t = 4-byte tag (UInt32)
#   hb_face_create takes an hb_blob_t* (the legacy raw-bytes signature
#   segfaults on all modern versions); hb_face_get_glyph_count (not
#   hb_face_count_glyphs).
# ccall library expressions must be constants in this build, so the
# symbols are resolved once with Libdl.dlopen/dlsym into function
# pointers (Libdl is portable across the supported OSes; a bare
# ccall to the `dlopen` symbol does not resolve on Windows).
#
# Shaped buffer order: logical for LTR runs, visual (left-to-right) for
# RTL runs (harfbuzz reverses RTL runs; cluster ids ascend/descend
# accordingly). Placement below uses the pen formulas per direction.
#
# Vendored Unicode 16.0.0 tables (BMP subset — same provenance protocol
# as the UAX#29 cluster tables in paragraph.jl, docs/TEXT_LAYOUT.md
# §3.2/§5.4/§9; generated, do not edit by hand):
#   _HB_SCRIPT_RANGES: Script property (Scripts.txt, primary script),
#     (start, stop, UAX#24 4-byte tag) triples, ascending by start.
#   _HB_BIDI_RANGES:   Bidi_Category (UnicodeData.txt field 5),
#     (start, stop, class code) triples; codes:
#       1=L 2=R 3=AL 4=EN 5=AN 6=CS 7=ES 8=ET 9=ON 10=BN 11=NSM
#       12=B 13=S 14=RLO 15=LRO 16=LRE 17=LRI 18=RRI 19=PDF 20=FSI
#       21=PDI 22=WS 23=RLE 24=RLI
#   _HB_MIRROR_PAIRS:  Bidi_Mirroring (BidiMirroring.txt),
#     (codepoint, mirror) pairs, ascending by codepoint.

"""A shaped glyph (docs/TEXT_LAYOUT.md §5.1): font GID plus font-unit
metrics as reported by the shaper (advance/offsets scale like
`getAdvance`; multiply by `scale(font)` for pixels)."""
struct ShapedGlyph
    gid::Int
    advance::Float32
    xOffset::Float32
    yOffset::Float32
end

# ---------- provider loading (D028/D033) ----------

const _HB_PKGID = Base.PkgId(
    Base.UUID("2e76f6c2-a576-52d4-95c1-20adfe4de566"), "HarfBuzz_jll")

const _HB_SYMBOLS = (
    :hb_blob_create, :hb_blob_destroy, :hb_face_create, :hb_face_destroy,
    :hb_font_create, :hb_font_destroy, :hb_buffer_create,
    :hb_buffer_destroy, :hb_buffer_set_direction, :hb_buffer_set_script,
    :hb_buffer_set_language, :hb_buffer_add, :hb_shape,
    :hb_buffer_get_glyph_infos, :hb_buffer_get_glyph_positions)

global _HB_FUNCS = nothing # Dict{Symbol,Ptr{Cvoid}}, once loaded
# Cached (blob, face, font) per parsed font: the raw bytes are already
# retained in `OtcOpenType.buf`, so one blob per typeface buffer.
global _HB_FACES = IdDict{OtcOpenType, NTuple{3, Ptr{Cvoid}}}()

"""HarfBuzz provider state, loaded on first use (lazy discovery, D028),
or a clear install hint (D033). Environments without HarfBuzz_jll load
normally and get the error only when shaping is engaged."""
function _requireHarfBuzz()
    global _HB_FUNCS
    _HB_FUNCS !== nothing && return
    if Base.locate_package(_HB_PKGID) === nothing
        throw(ErrorException(
            "Shaping support is opt-in: add the HarfBuzz_jll package to " *
            "your environment (Pkg.add(\"HarfBuzz_jll\")) and retry"))
    end
    m = Base.require(_HB_PKGID)
    path = Base.invokelatest(_hbLibPath, m)
    # Libdl diagnostics name the path/symbol and the OS cause; let them
    # propagate. The handle must outlive the resolved pointers, so it is
    # closed only when symbol resolution fails (the cache is never
    # populated).
    handle = Libdl.dlopen(path, Libdl.RTLD_NOW)
    funcs = Dict{Symbol, Ptr{Cvoid}}()
    loaded = false
    try
        for s in _HB_SYMBOLS
            funcs[s] = Libdl.dlsym(handle, String(s))
        end
        loaded = true
    finally
        loaded || Libdl.dlclose(handle)
    end
    _HB_FUNCS = funcs
    return nothing
end

_hbLibPath(m) = m.libharfbuzz # String path (JLLWrappers 1.7 style)

"""Cached (blob, face, font) for `ot`'s raw bytes (created once)."""
function _hbFace(ot::OtcOpenType)
    get(_HB_FACES, ot) do
        blob = ccall(_HB_FUNCS[:hb_blob_create], Ptr{Cvoid},
            (Ptr{Cchar}, UInt32, UInt32, Ptr{Cvoid}, Ptr{Cvoid}),
            ot.buf, UInt32(length(ot.buf)), 0, C_NULL, C_NULL) # DUPLICATE
        blob === C_NULL &&
            throw(ErrorException(
                "HarfBuzz: hb_blob_create failed for $(length(ot.buf)) font bytes"))
        face = ccall(_HB_FUNCS[:hb_face_create], Ptr{Cvoid},
            (Ptr{Cvoid}, UInt32), blob, 0)
        face === C_NULL &&
            throw(ErrorException(
                "HarfBuzz: hb_face_create failed (unsupported font data?)"))
        font = ccall(_HB_FUNCS[:hb_font_create], Ptr{Cvoid},
            (Ptr{Cvoid},), face)
        return (blob, face, font)
    end
end

"""Shape one run of codepoints against `ot`'s raw bytes. Returns the
buffer-order glyph arrays `(gids, clusters, xadv, xoff, yoff)` in font
units; `clusters` are 0-based indices into `codepoints`."""
function _hbShape(ot::OtcOpenType, codepoints::Vector{UInt32},
    script::UInt32, direction::UInt32, lang::String)
    (blob, face, font) = _hbFace(ot)
    buf = ccall(_HB_FUNCS[:hb_buffer_create], Ptr{Cvoid}, ())
    ccall(_HB_FUNCS[:hb_buffer_set_direction], Cvoid,
        (Ptr{Cvoid}, UInt32), buf, direction)
    ccall(_HB_FUNCS[:hb_buffer_set_script], Cvoid,
        (Ptr{Cvoid}, UInt32), buf, script)
    lc = Vector{Cchar}(vcat([Cchar(c) for c in lang], Cchar(0)))
    ccall(_HB_FUNCS[:hb_buffer_set_language], Cvoid,
        (Ptr{Cvoid}, Ptr{Cchar}), buf, lc)
    for (i, cp) in enumerate(codepoints)
        ccall(_HB_FUNCS[:hb_buffer_add], Cvoid,
            (Ptr{Cvoid}, UInt32, UInt32), buf, cp, UInt32(i - 1))
    end
    ccall(_HB_FUNCS[:hb_shape], Cvoid,
        (Ptr{Cvoid}, Ptr{Cvoid}, Ptr{Cvoid}, UInt32), font, buf, C_NULL, 0)
    nref = Ref{UInt32}(0)
    infoptr = ccall(_HB_FUNCS[:hb_buffer_get_glyph_infos], Ptr{UInt32},
        (Ptr{Cvoid}, Ptr{UInt32}), buf, nref)
    n = Int(nref[])
    poss = ccall(_HB_FUNCS[:hb_buffer_get_glyph_positions], Ptr{Int32},
        (Ptr{Cvoid}, Ptr{UInt32}), buf, nref)
    gids = Vector{UInt32}(undef, n)
    clusters = Vector{UInt32}(undef, n)
    xadv = Vector{Int32}(undef, n)
    xoff = Vector{Int32}(undef, n)
    yoff = Vector{Int32}(undef, n)
    for i in 1:n
        # 1-based index of field k of glyph i (stride 5) = 5i - 4 + k
        gids[i] = unsafe_load(infoptr, 5i - 4)
        clusters[i] = unsafe_load(infoptr, 5i - 2)
        xadv[i] = unsafe_load(poss, 5i - 4)
        xoff[i] = unsafe_load(poss, 5i - 2)
        yoff[i] = unsafe_load(poss, 5i - 1)
    end
    ccall(_HB_FUNCS[:hb_buffer_destroy], Cvoid, (Ptr{Cvoid},), buf)
    return (gids, clusters, xadv, xoff, yoff)
end

# ---------- script / bidi / mirroring (vendored tables below) ----------

"""UAX#24 4-byte script tag of `cp` (BMP table; astral → Zyyy)."""
function _hbScript(cp::UInt32)
    cp > 0xffff && return 0x5a797979 # Zyyy
    vals = _HB_SCRIPT_RANGES
    n = length(vals) ÷ 3
    lo, hi = 1, n
    while lo <= hi
        mid = (lo + hi) ÷ 2
        s = vals[3mid - 2]
        e = vals[3mid - 1]
        if cp < s
            hi = mid - 1
        elseif cp > e
            lo = mid + 1
        else
            return vals[3mid]
        end
    end
    return 0x5a797979
end

"""Script of a run: first non-neutral codepoint (Zyyy/Zinh are neutral —
§5.4); Zyyy when none."""
function _hbScriptOf(codepoints)
    for cp in codepoints
        s = _hbScript(cp)
        s != 0x5a797979 && s != 0x5a696e68 && return s
    end
    return 0x5a797979
end

"""Default language per script (§5.4: "language defaults to the script's
default"); en elsewhere."""
function _hbDefaultLanguage(script::UInt32)
    script == 0x41726162 && return "ar" # Arab
    script == 0x44657661 && return "hi" # Deva
    script == 0x4c61746e && return "en" # Latn
    script == 0x48616e69 && return "zh" # Hani
    return "en"
end

"""UAX#9 Bidi_Category code of `cp` (BMP table; astral → ON)."""
function _hbBidiClass(cp::UInt32)
    cp > 0xffff && return 9
    vals = _HB_BIDI_RANGES
    n = length(vals) ÷ 3
    lo, hi = 1, n
    while lo <= hi
        mid = (lo + hi) ÷ 2
        s = vals[3mid - 2]
        e = vals[3mid - 1]
        if cp < s
            hi = mid - 1
        elseif cp > e
            lo = mid + 1
        else
            return vals[3mid]
        end
    end
    return 9
end

"""Simplified UAX#9 (v1, §5.3): strong clusters take their own
direction (L/EN/AN → 4, R/AL → 5); neutrals, controls, and astral
codepoints take the paragraph base direction. No explicit controls
(RLO/LRI/…) in v1 — documented limit."""
function _hbResolvedDir(codepoints, baseDir::UInt32)
    dir = baseDir
    for cp in codepoints
        c = _hbBidiClass(cp)
        if c == 1 || c == 4 || c == 5 # L, EN, AN
            dir = 4
            break
        elseif c == 2 || c == 3 # R, AL
            dir = 5
            break
        end
    end
    return dir
end

"""Bidi_Mirroring (UAX#9 L2) of `cp`; identity when not mirrored."""
function _hbMirror(cp::UInt32)
    cp > 0xffff && return cp
    vals = _HB_MIRROR_PAIRS
    n = length(vals) ÷ 2
    lo, hi = 1, n
    while lo <= hi
        mid = (lo + hi) ÷ 2
        s = vals[2mid - 1]
        if cp < s
            hi = mid - 1
        elseif cp > s
            lo = mid + 1
        else
            return vals[2mid]
        end
    end
    return cp
end

# ---------- public shaper interface (§5.1) ----------

"""
shapeText(tf, codepoints; script = nothing, direction = LeftToRight,
language = nothing)

Shaper interface (docs/TEXT_LAYOUT.md §5.1): consumes `tf`'s raw font
bytes plus one run's codepoints, a script, language, and direction;
returns `Vector{Vector{ShapedGlyph}}` — one entry per cluster in
**logical cluster order** (ascending cluster id; harfbuzz's buffer is
visual order for RTL runs, so RTL entries are reversed); within an
entry the glyphs keep the shaper's buffer order. `script` is a UAX#24
4-byte tag (UInt32, e.g. `0x41726162` "Arab"); it defaults to the first
non-neutral codepoint of the run (§5.4). `language` defaults to the
script's default. Raises the D033 install hint when the provider is
not installed.
"""
function shapeText(tf::Typeface, codepoints::Vector{UInt32};
    script::Union{UInt32, Nothing} = nothing,
    direction::TextDirection = LeftToRight,
    language::Union{String, Nothing} = nothing)
    isempty(codepoints) && return Vector{Vector{ShapedGlyph}}()
    script === nothing && (script = _hbScriptOf(codepoints))
    language === nothing && (language = _hbDefaultLanguage(script))
    _requireHarfBuzz()
    return Base.invokelatest(_shapeTextKernel, tf, codepoints, script,
        UInt32(direction === RightToLeft ? 5 : 4), language)
end

function _shapeTextKernel(tf, codepoints, script, direction, language)
    (gids, clusters, xadv, xoff, yoff) =
        _hbShape(tf.opentype, codepoints, script, direction, language)
    n = length(gids)
    out = Vector{Vector{ShapedGlyph}}()
    n == 0 && return out
    seq = direction == 4 ? (1:n) : (n:-1:1) # logical (ascending cluster) order
    i = first(seq)
    curC = clusters[i]
    cur = Vector{ShapedGlyph}()
    for idx in seq
        c = clusters[idx]
        if c != curC
            push!(out, cur)
            cur = Vector{ShapedGlyph}()
            curC = c
        end
        push!(cur, ShapedGlyph(Int(gids[idx]), Float32(xadv[idx]),
            Float32(xoff[idx]), Float32(yoff[idx])))
    end
    push!(out, cur)
    return out
end

"""
glyphPathByGid(tf, gid)

GID → native outline (§5.1): reads the glyf table by index through the
existing internal reader (no cmap); `gid` < 0, ≥ the font's glyph count,
or 0 → the `.notdef` outline. Fresh path per call, in image
coordinates (Y-flipped, as `getGlyphPath`), unscaled font units. CFF/TTC
fonts stay rejected (parse-time, D015).
"""
function glyphPathByGid(tf::Typeface, gid::Int)
    ot = tf.opentype
    n = length(ot.glyf.offsets)
    g = gid < 0 || gid >= n ? 0 : gid
    path = _otParseGlyfGlyph(ot, UInt16(g))
    transform(path, scale(Vec2(Float32(1), Float32(-1))))
    return path
end

