# ---------- shaped paragraph layout (§5.3, §2.1) ----------
# (_ShapedEntryPos/_ShapedLinePos live in paragraph.jl — see there.)

"""A logical entry: kept codepoints, span index, and the entry's
codepoint range in the span text `[first, last)` (the Cluster fields)."""
struct _ShapedEntry
    cps::Vector{UInt32}
    span::Int
    first::Int
    last::Int
end

_isNL(e::_ShapedEntry) = length(e.cps) == 1 && e.cps[1] == 0x0a

"""True when any kept codepoint has a strong-RTL bidi class (R/AL) —
the LTR engagement test (§5.3: LTR text with strong RTL content shapes
when the provider is present, legacy isolated-forms rendering when
absent — the T028 documented limit)."""
function _hasStrongRtl(spans)
    for span in spans
        for cp in _otCodepoints(span.text)
            cp < 0x20 && continue
            c = _hbBidiClass(cp)
            if c == 2 || c == 3
                return true
            end
        end
    end
    return false
end

"""One empty shaped line (no kept codepoints; box from the first
layout span's font, as the legacy empty-paragraph case)."""
function _shapedEmptyLayout(p::Paragraph, spans)
    asc = Float32(0)
    desc = Float32(0)
    if !isempty(spans)
        asc, desc = _lineBoxOfFont(spans[1].font)
    end
    line = ParagraphLine(1:0, asc, desc, Float32(0))
    slp = _ShapedLinePos(Int[], _ShapedEntryPos[], Int[], asc)
    shapedFonts = [sp.font for sp in spans]
    return ParagraphLayout(p, Cluster[], [line],
        Arrangement(Tuple{Int, Int}[], Tuple{Int, Int}[],
            Font[], UInt32[], Vec2[], Rect[]),
        Tuple{UnitRange{Int}, Int}[], [Int[]], [slp], shapedFonts)
end

"""Lay out a paragraph through the shaper (engaged by `layoutParagraph`
for RTL paragraphs and for LTR paragraphs with strong RTL content).
Wrapping uses the full-paragraph shaped advances; each line is then
re-shaped (contextual forms at line ends — §2.1/§5.2).
`shortcut: shaped EllipsisOverflow renders as plain clip — the
ellipsis pass is typeset-based; revisit when shaped text needs it.`"""
function _shapedLayout(p::Paragraph)
    _requireHarfBuzz()
    spans = _layoutSpans(p)
    baseDir = UInt32(p.dir === RightToLeft ? 5 : 4)

    # ---- logical cluster stream (typeset keeps cp >= 0x20 and \n) ----
    entries = Vector{_ShapedEntry}()
    for (s, span) in enumerate(spans)
        keptCps = UInt32[]
        keptIdx = Int[]
        for (idx, cp) in enumerate(_otCodepoints(span.text))
            cp >= 0x20 || cp == 0x0a || continue
            push!(keptCps, cp)
            push!(keptIdx, idx)
        end
        nK = length(keptCps)
        k = 1
        for i in 2:nK
            if _canBreakCluster(keptCps[i - 1], keptCps[i])
                push!(entries, _ShapedEntry(
                    keptCps[k:i - 1], s, keptIdx[k], keptIdx[i - 1] + 1))
                k = i
            end
        end
        if nK > 0
            push!(entries, _ShapedEntry(
                keptCps[k:nK], s, keptIdx[k], keptIdx[nK] + 1))
        end
    end
    n = length(entries)
    if n == 0
        return _shapedEmptyLayout(p, spans)
    end

    # ---- per entry: script (first non-neutral, §5.4) and resolved
    #      direction (simplified UAX#9, §5.3) ----
    entryScript = Vector{UInt32}(undef, n)
    for i in 1:n
        s = 0x5a797979 # Zyyy
        for cp in entries[i].cps
            t = _hbScript(cp)
            if t != 0x5a797979 && t != 0x5a696e68 # not Zyyy/Zinh
                s = t
                break
            end
        end
        if s == 0x5a797979 && i > 1
            s = entryScript[i - 1] # neutral-only entry inherits the run
        end
        entryScript[i] = s
    end
    entryDir = Vector{UInt32}(undef, n)
    for i in 1:n
        entryDir[i] = _isNL(entries[i]) ? baseDir :
            _hbResolvedDir(entries[i].cps, baseDir)
    end

    # ---- advance per entry (wrap estimate, full-paragraph context);
    #      each (span, script, dir) run shapes exactly once ----
    entryAdv = Vector{Float32}(undef, n)
    i = 1
    while i <= n
        if _isNL(entries[i])
            f = spans[entries[i].span].font
            entryAdv[i] = getAdvance(f.typeface, 0x20) * scale(f)
            i += 1
            continue
        end
        j = i
        while j < n && !_isNL(entries[j + 1]) &&
            entries[j + 1].span == entries[i].span &&
            entryScript[j + 1] == entryScript[i] &&
            entryDir[j + 1] == entryDir[i]
            j += 1
        end
        cps = UInt32[]
        for k in i:j
            for cp in entries[k].cps
                push!(cps, entryDir[i] == 5 ? _hbMirror(cp) : cp)
            end
        end
        ot = spans[entries[i].span].font.typeface.opentype
        (gids, clusters, xadv, xoff, yoff) = _hbShape(
            ot, cps, entryScript[i], entryDir[i],
            _hbDefaultLanguage(entryScript[i]))
        off = 0
        for k in i:j
            c0 = off
            c1 = off + length(entries[k].cps) - 1
            a = 0
            for g in eachindex(gids)
                if clusters[g] >= c0 && clusters[g] <= c1
                    a += xadv[g]
                end
            end
            entryAdv[k] = Float32(a) * scale(spans[entries[k].span].font)
            off = c1 + 1
        end
        i = j + 1
    end

    # ---- wrap (typeset rules, §2.1, in cluster units) ----
    lines = Vector{Vector{Int}}()
    if p.width > 0
        cur = Int[]
        pen = Float32(0)
        lastWS = 0
        for idx in 1:n
            if _isNL(entries[idx])
                push!(cur, idx)
                push!(lines, cur)
                cur = Int[]
                pen = Float32(0)
                lastWS = 0
                continue
            end
            adv = entryAdv[idx]
            allWS = all(c -> _canWrap(c), entries[idx].cps)
            spOnly = allWS && all(c -> c == 0x20, entries[idx].cps)
            if !spOnly && pen + adv > p.width && !isempty(cur)
                if lastWS > 0
                    push!(lines, cur[1:lastWS])
                    keep = cur[lastWS + 1:end]
                    pen = Float32(0)
                    for k in keep
                        pen += entryAdv[k]
                    end
                    cur = keep
                else
                    push!(lines, cur)
                    cur = Int[]
                    pen = Float32(0)
                end
                lastWS = 0
            end
            push!(cur, idx)
            pen += adv
            if allWS
                lastWS = length(cur)
            end
        end
        push!(lines, cur)
    else
        push!(lines, collect(1:n))
    end

    # ---- line boxes and baselines (typeset's vertical pass, §2.4) ----
    nLines = length(lines)
    lineAsc = Vector{Float32}(undef, nLines)
    lineDesc = Vector{Float32}(undef, nLines)
    lineLH = Vector{Float32}(undef, nLines)
    for (li, line) in enumerate(lines)
        asc = Float32(0)
        desc = Float32(0)
        lh = Float32(0)
        seen = Set{Int}()
        for idx in line
            sp = entries[idx].span
            sp in seen && continue
            push!(seen, sp)
            f = spans[sp].font
            offset, d = _lineBoxOfFont(f)
            asc = max(asc, offset)
            desc = max(desc, d)
            fh = f.lineHeight >= 0 ? f.lineHeight : defaultLineHeight(f)
            lh = max(lh, fh)
        end
        if isempty(seen) && !isempty(spans)
            asc, desc = _lineBoxOfFont(spans[1].font)
            f1 = spans[1].font
            lh = f1.lineHeight >= 0 ? f1.lineHeight :
                defaultLineHeight(f1)
        end
        lineAsc[li] = asc
        lineDesc[li] = desc
        lineLH[li] = lh
    end
    baseline = lineAsc[1]
    baselines = Vector{Float32}(undef, nLines)
    baselines[1] = baseline
    for li in 2:nLines
        baseline += lineLH[li - 1]
        baselines[li] = baseline
    end

    # ---- alignment (§2.5, effective only when width > 0) ----
    xAdj = Vector{Float32}(undef, nLines)
    for (li, line) in enumerate(lines)
        cw = Float32(0)
        for idx in line
            _isNL(entries[idx]) && continue
            all(c -> _canWrap(c), entries[idx].cps) ||
                (cw += entryAdv[idx])
        end
        if p.width > 0
            if p.hAlign === CenterAlign
                xAdj[li] = (p.width - cw) / Float32(2)
            elseif p.hAlign === RightAlign
                xAdj[li] = p.width - cw
            else
                xAdj[li] = Float32(0)
            end
        else
            xAdj[li] = Float32(0)
        end
    end

    # ---- vertical alignment (typeset's final pass) ----
    yAdj = Float32(0)
    if p.height > 0
        lastLine = lines[end]
        lastIdx = isempty(lastLine) ? 0 : lastLine[end]
        while lastIdx > 0 && _isNL(entries[lastIdx])
            lastIdx -= 1
        end
        if lastIdx > 0
            f = spans[entries[lastIdx].span].font
            offset = Float32(roundHalfAway((ascent(f.typeface) +
                lineGap(f) / Float32(2)) * scale(f)))
            lh = f.lineHeight >= 0 ? f.lineHeight : defaultLineHeight(f)
            furthestY = baselines[end] - offset + lh
            if p.vAlign === MiddleAlign
                yAdj = Float32(roundHalfAway((p.height - furthestY) /
                    Float32(2)))
            elseif p.vAlign === BottomAlign
                yAdj = p.height - furthestY
            end
        end
    end

    # ---- per-line re-shaping and placement ----
    shapedPos = Vector{_ShapedLinePos}(undef, nLines)
    for (li, line) in enumerate(lines)
        baselineY = baselines[li] + yAdj
        # shape the line's (span, script, dir) runs — line context
        # gives contextual forms at line ends
        runGlyphs = Dict{Int, Vector{Tuple{Int, Float32, Float32, Float32}}}()
        if !isempty(line)
            s0 = line[1]
            for idx in line[2:end]
                if entries[idx].span != entries[s0].span ||
                    entryScript[idx] != entryScript[s0] ||
                    entryDir[idx] != entryDir[s0]
                    _shapedRunGlyphs(runGlyphs, spans, entries,
                        entryScript, entryDir, s0, idx - 1)
                    s0 = idx
                end
            end
            _shapedRunGlyphs(runGlyphs, spans, entries, entryScript,
                entryDir, s0, line[end])
        end
        # visual (L2R) order: simplified UAX#9 segments (§5.3)
        order = Int[]
        if !isempty(line)
            segs = Vector{Tuple{Int, Int, UInt32}}()
            s0 = line[1]
            for idx in line[2:end]
                if entryDir[idx] != entryDir[s0]
                    push!(segs, (s0, idx - 1, entryDir[s0]))
                    s0 = idx
                end
            end
            push!(segs, (s0, line[end], entryDir[s0]))
            if baseDir == 4
                for (a, b, d) in segs
                    if d == 4
                        append!(order, a:b)
                    else
                        append!(order, b:-1:a)
                    end
                end
            else
                for k in length(segs):-1:1
                    (a, b, d) = segs[k]
                    if d == 5
                        append!(order, b:-1:a)
                    else
                        append!(order, a:b)
                    end
                end
            end
        end
        # placement: blocks = consecutive visual entries sharing
        # (span, script, dir). The buffer is already in visual order
        # for RTL runs (harfbuzz reverses them), so the pen walks
        # forward in buffer order for BOTH directions — the exact
        # placement of harfbuzz's own cairo bridge
        # (hb_cairo_glyphs_from_buffer, harfbuzz 12.3.2):
        #   x = pen + Σ(adv of earlier glyphs) + xoff
        pos = Vector{_ShapedEntryPos}(undef, length(order))
        vSpans = Vector{Int}(undef, length(order))
        pen = xAdj[li]
        v = 1
        while v <= length(order)
            e0 = order[v]
            v1 = v
            while v1 < length(order) &&
                entries[order[v1 + 1]].span == entries[e0].span &&
                entryScript[order[v1 + 1]] == entryScript[e0] &&
                entryDir[order[v1 + 1]] == entryDir[e0]
                v1 += 1
            end
            block = order[v:v1]
            glyphs = Tuple{Int, Float32, Float32, Float32}[]
            starts = Int[]
            for k in block
                push!(starts, length(glyphs) + 1)
                append!(glyphs, get(runGlyphs, k,
                    Tuple{Int, Float32, Float32, Float32}[]))
            end
            push!(starts, length(glyphs) + 1)
            blockW = Float32(sum(g[4] for g in glyphs))
            xOf = Vector{Float32}(undef, length(glyphs))
            for gi in 1:length(glyphs)
                xOf[gi] = pen + _sumAdv(glyphs, 1, gi - 1) + glyphs[gi][2]
            end
            beforeAdv = Float32(0)
            for (t, k) in enumerate(block)
                lo = starts[t]
                hi = starts[t + 1] - 1
                epGlyphs = Tuple{Int, Float32, Float32, Float32}[]
                r0 = Float32(NaN)
                r1 = Float32(NaN)
                for gi in lo:hi
                    (gid, yo, adv) = (glyphs[gi][1], glyphs[gi][3],
                        glyphs[gi][4])
                    push!(epGlyphs, (gid, xOf[gi], yo, adv))
                    if isnan(r0)
                        r0 = xOf[gi]
                        r1 = xOf[gi] + adv
                    else
                        r0 = min(r0, xOf[gi])
                        r1 = max(r1, xOf[gi] + adv)
                    end
                end
                if isempty(epGlyphs)
                    r0 = pen + beforeAdv
                    r1 = r0
                end
                ws = all(c -> _canWrap(c), entries[k].cps)
                pos[v + t - 1] = _ShapedEntryPos(epGlyphs, r0, r1, ws)
                vSpans[v + t - 1] = entries[k].span
                beforeAdv += _sumAdv(glyphs, lo, hi)
            end
            pen += blockW
            v = v1 + 1
        end
        shapedPos[li] = _ShapedLinePos(order, pos, vSpans, baselineY)
    end

    # ---- ParagraphLayout ----
    clusters = Vector{Cluster}(undef, n)
    for (i, e) in enumerate(entries)
        clusters[i] = Cluster(e.span, e.first, e.last)
    end
    plines = Vector{ParagraphLine}(undef, nLines)
    for (li, line) in enumerate(lines)
        cw = Float32(0)
        for idx in line
            _isNL(entries[idx]) && continue
            all(c -> _canWrap(c), entries[idx].cps) ||
                (cw += entryAdv[idx])
        end
        cFirst = isempty(line) ? 1 : line[1]
        cLast = isempty(line) ? 0 : line[end]
        plines[li] = ParagraphLine(cFirst:cLast, lineAsc[li],
            lineDesc[li], cw)
    end
    arrangement = Arrangement(Tuple{Int, Int}[], Tuple{Int, Int}[],
            Font[], UInt32[], Vec2[], Rect[])
    shapedPerm = [copy(slp.order) for slp in shapedPos]
    shapedFonts = [sp.font for sp in spans]
    return ParagraphLayout(p, clusters, plines, arrangement,
        Tuple{UnitRange{Int}, Int}[],
        shapedPerm, shapedPos, shapedFonts)
end

"""Shape one (span, script, dir) run of a line (entries r0..r1) and
record each entry's glyphs `(gid, xoff*s, -yoff*s, xadv*s)` (buffer
order, scaled to the entry's font) under its entry index. NL entries
never shape."""
function _shapedRunGlyphs(runGlyphs, spans, entries, entryScript,
    entryDir, r0::Int, r1::Int)
    if _isNL(entries[r0])
        return nothing
    end
    cps = UInt32[]
    for k in r0:r1
        if _isNL(entries[k])
            continue
        end
        for cp in entries[k].cps
            push!(cps, entryDir[r0] == 5 ? _hbMirror(cp) : cp)
        end
    end
    isempty(cps) && return nothing
    ot = spans[entries[r0].span].font.typeface.opentype
    (gids, clusters, xadv, xoff, yoff) = _hbShape(
        ot, cps, entryScript[r0], entryDir[r0],
        _hbDefaultLanguage(entryScript[r0]))
    off = 0
    for k in r0:r1
        if _isNL(entries[k])
            continue
        end
        c0 = off
        c1 = off + length(entries[k].cps) - 1
        s = scale(spans[entries[k].span].font)
        gl = Vector{Tuple{Int, Float32, Float32, Float32}}()
        for g in eachindex(gids)
            if clusters[g] >= c0 && clusters[g] <= c1
                push!(gl, (Int(gids[g]), Float32(xoff[g]) * s,
                    Float32(-yoff[g]) * s, Float32(xadv[g]) * s))
            end
        end
        runGlyphs[k] = gl
        off = c1 + 1
    end
    return nothing
end

"""Sum of glyph advances in `glyphs[lo:hi]` (0 when lo > hi)."""
function _sumAdv(glyphs, lo::Int, hi::Int)
    lo > hi && return Float32(0)
    a = Float32(0)
    for i in lo:hi
        a += glyphs[i][4]
    end
    return a
end

# ---------- shaped rendering ----------

"""Render the shaped lines of a layout into `target` (fill or stroke),
one path per touched span so per-run paints apply (as `computePaths`
does for the legacy path). Decorations use the cluster selection
rects (§5.1); the whitespace entry at a line end is undecorated (the
legacy rule)."""
function _shapedUber(target::Image, l::ParagraphLayout, mat::Mat3,
    stroke::Bool; strokeWidth::Float32 = Float32(1),
    lineCap::LineCap = ButtCap, lineJoin::LineJoin = MiterJoin,
    miterLimit::Float32 = defaultMiterLimit,
    dashes::Vector{Float32} = Vector{Float32}())
    fonts = l.shapedFonts
    for (li, slp) in enumerate(l.shapedPos)
        lastC = li in eachindex(l.lines) ? l.lines[li].clusters.stop : 0
        paths = Dict{Int, Path}()
        for (vi, eIdx) in enumerate(slp.order)
            sp = slp.spans[vi]
            font = fonts[sp]
            tf = font.typeface
            s = scale(font)
            ep = slp.pos[vi]
            path = get!(paths, sp) do
                newPath()
            end
            underlineThickness = _underlineThickness(tf) * s
            underlinePosition = _underlinePosition(tf) * s
            strikeoutThickness = _strikeoutThickness(tf) * s
            strikeoutPosition = _strikeoutPosition(tf) * s
            applyDeco = !(ep.ws && eIdx == lastC)
            for (gid, x, y, adv) in ep.glyphs
                gpath = glyphPathByGid(tf, gid)
                transform(gpath, translate(Vec2(x, slp.baselineY + y)) *
                    scale(Vec2(s, s)))
                addPath(path, gpath)
            end
            if applyDeco && !isempty(ep.glyphs)
                srX = ep.rectX0
                srW = ep.rectX1 - ep.rectX0
                if font.underline
                    rect(path, srX, slp.baselineY - underlinePosition +
                        underlineThickness / Float32(2),
                        srW, underlineThickness, clockwise = isCCW(tf))
                end
                if font.strikethrough
                    rect(path, srX, slp.baselineY - strikeoutPosition,
                        srW, strikeoutThickness, clockwise = isCCW(tf))
                end
            end
        end
        for sp in sort(collect(keys(paths)))
            path = paths[sp]
            font = fonts[sp]
            for paint in font.paints
                if stroke
                    strokePath(target, path, paint; transform = mat,
                        strokeWidth = strokeWidth, lineCap = lineCap,
                        lineJoin = lineJoin, miterLimit = miterLimit,
                        dashes = dashes)
                else
                    fillPath(target, path, paint; transform = mat)
                end
            end
        end
    end
    return nothing
end
