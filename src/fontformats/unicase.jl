# Case mapping for Font.textCase (T009).
#
# Port of the pinned Nim 2.2.6 stdlib one-rune case tables and lookup
# (nim/lib/pure/includes/unicode_ranges.nim + unicode.nim binarySearch/
# toUpper/toLower): upstream fonts.nim convertTextCase calls Rune.toUpper/
# toLower on each rune. Tables generated verbatim; the delta entries are
# encoded as (target - source + 500), and the lookup subtracts 500.

function _unicaseBinarySearch(c, tab::AbstractVector{Int32}, stride)
    n = div(length(tab), stride) # entry count
    t = 0 # 0-based flat index of the left entry
    while n > 1
        m = div(n, 2)
        p = t + m * stride
        if c >= tab[p + 1]
            t = p
            n = n - m
        else
            n = m
        end
    end
    if n != 0 && c >= tab[t + 1]
        return t
    end
    return -1
end

function _unicaseLower(c::Integer)
    c = Int(c)
    p = _unicaseBinarySearch(c, _UNICASE_TOLOWERRANGES, 3)
    if p >= 0 && c >= _UNICASE_TOLOWERRANGES[p + 1] &&
        c <= _UNICASE_TOLOWERRANGES[p + 2]
        return c + _UNICASE_TOLOWERRANGES[p + 3] - 500
    end
    p = _unicaseBinarySearch(c, _UNICASE_TOLOWERSINGLETS, 2)
    if p >= 0 && c == _UNICASE_TOLOWERSINGLETS[p + 1]
        return c + _UNICASE_TOLOWERSINGLETS[p + 2] - 500
    end
    return c
end

function _unicaseUpper(c::Integer)
    c = Int(c)
    p = _unicaseBinarySearch(c, _UNICASE_TOUPPERRANGES, 3)
    if p >= 0 && c >= _UNICASE_TOUPPERRANGES[p + 1] &&
        c <= _UNICASE_TOUPPERRANGES[p + 2]
        return c + _UNICASE_TOUPPERRANGES[p + 3] - 500
    end
    p = _unicaseBinarySearch(c, _UNICASE_TOUPPERSINGLETS, 2)
    if p >= 0 && c == _UNICASE_TOUPPERSINGLETS[p + 1]
        return c + _UNICASE_TOUPPERSINGLETS[p + 2] - 500
    end
    return c
end
